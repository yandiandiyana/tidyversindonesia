P_GEOM = {
    'mapping': 'Pemetaan estetika, dibuat dengan [grf_estetika()]; bila kosong, memakai pemetaan dari [vis_ggplot()].',
    'data': 'Data untuk lapisan ini; bila kosong, memakai data dari [vis_ggplot()].',
    '...': ('Estetika tetap (misalnya `warna = "blue"`) dan argumen lain. Nama estetika lokal '
            '(`warna`, `isian`, `bentuk`, `ukuran`, `alfa`, `tipe_garis`, `ketebalan_garis`, '
            '`kelompok`) diterjemahkan; nama lain, termasuk nama asli berbahasa Inggris, '
            'diteruskan apa adanya.'),
}
def _geom(nama, fungsi, judul, contoh, intro=None, p=None, **kw):
    d = dict(nama=nama, paket='ggplot2', fungsi=fungsi, keluarga='grf', judul=judul,
             estetika=True, contoh=contoh,
             ret='Sebuah lapisan ggplot yang ditambahkan dengan `+`, sama seperti [ggplot2::%s()].' % fungsi,
             p=dict(P_GEOM, **(p or {})))
    if intro:
        d['intro'] = intro
    d.update(kw)
    return d


