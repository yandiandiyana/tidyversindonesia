_RET_TIBBLE = 'Sebuah tibble, sama seperti [readr::%s()].'
_ASAL = 'Hasil pembacaan (tibble) yang diperiksa.'


def _baca(nama, fungsi, judul, contoh, intro=None, ret=None, **kw):
    d = dict(nama=nama, paket='readr', fungsi=fungsi, keluarga='imp', judul=judul,
             contoh=contoh, ret=ret or (_RET_TIBBLE % fungsi),
             p={})
    if intro:
        d['intro'] = intro
    d.update(kw)
    return d


def _kolom(nama, fungsi, judul, contoh, intro=None, **kw):
    d = dict(nama=nama, paket='readr', fungsi=fungsi, keluarga='imp', judul=judul,
             contoh=contoh, ret='Sebuah spesifikasi tipe kolom, sama seperti [readr::%s()].' % fungsi,
             p={})
    if intro:
        d['intro'] = intro
    d.update(kw)
    return d


